let LANG = 'en';

function setLang(code) {
  LANG = I18N[code] ? code : 'en';
  document.documentElement.lang = LANG;
}

function t(key, params) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
  return s;
}

// First of the device's preferred languages that we have texts for.
function detectLang() {
  for (const l of navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en']) {
    const code = String(l).slice(0, 2).toLowerCase();
    if (I18N[code]) return code;
  }
  return 'en';
}

const locale = () => (LANG === 'de' ? 'de-DE' : 'en-GB');

// Fills elements marked in index.html: data-i18n (text), data-i18n-html (trusted markup),
// data-i18n-attr="attribute:key;attribute:key".
function applyStatic() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr, t(key));
    }
  });
}
